export function getStoredPartnerCompany() {
  try {
    const raw = sessionStorage.getItem(PARTNER_STORAGE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    return PARTNER_COMPANIES.find((c) => c.id === parsed?.id) || parsed || null;
  } catch {
    return null;
  }
}

export function setStoredPartnerCompany(company) {
  try {
    if (company) {
      sessionStorage.setItem(PARTNER_STORAGE_KEY, JSON.stringify(company));
    } else {
      sessionStorage.removeItem(PARTNER_STORAGE_KEY);
    }
  } catch {
    // Ignore storage error
  }
}

export function clearStoredPartnerCompany() {
  try {
    sessionStorage.removeItem(PARTNER_STORAGE_KEY);
  } catch {
    // Ignore storage error
  }
}
